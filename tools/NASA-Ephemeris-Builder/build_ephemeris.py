#!/usr/bin/env python3
"""
Build the compact offline ephemeris for Chiron, Ceres, Pallas, Juno and Vesta
from NASA/JPL Horizons. Writes ../js/ephemeris.js.

Run (internet needed only now, not when the site is used):
    py build_ephemeris.py

Data: heliocentric geometric positions, J2000 ecliptic, AU, UT, one sample
every 16 days from 1800-01-01 to 2101-01-15, stored as integers in 1e-6 AU
(base64, little-endian int32, x y z interleaved). The browser interpolates
with 8-point Lagrange and applies light-time and aberration itself.
"""

import base64
import csv
import io
import json
import math
import struct
import time
import urllib.parse
import urllib.request
from pathlib import Path

API = "https://ssd.jpl.nasa.gov/api/horizons.api"
JD0 = 2378496.5          # 1800-01-01 00:00 UT
STEP = 16                # days; must match js/app.js (read from EPH.step)
COUNT = 6873             # last sample = JD0 + 6872*16 = 2101-01-15
CHUNK = 400              # samples per request
SCALE = 1e-6             # AU per integer unit
OUTPUT = Path(__file__).resolve().parent.parent / "js" / "ephemeris.js"

# (key in EPH.names, Horizons small-body command, plausible distance range in AU)
BODIES = [
    ("chiron", "2060;", (5.0, 25.0)),
    ("ceres",  "1;",    (1.5, 4.5)),
    ("pallas", "2;",    (1.5, 4.5)),
    ("juno",   "3;",    (1.5, 4.5)),
    ("vesta",  "4;",    (1.5, 4.5)),
]


def fetch(command, first, count):
    start = JD0 + first * STEP
    stop = JD0 + (first + count - 1) * STEP
    params = {
        "format": "json", "COMMAND": f"'{command}'", "OBJ_DATA": "'NO'",
        "MAKE_EPHEM": "'YES'", "EPHEM_TYPE": "'VECTORS'", "CENTER": "'500@10'",
        "START_TIME": f"'JD {start:.1f}'", "STOP_TIME": f"'JD {stop:.1f}'",
        "STEP_SIZE": f"'{STEP} d'", "TIME_TYPE": "'UT'", "REF_SYSTEM": "'ICRF'",
        "REF_PLANE": "'ECLIPTIC'", "OUT_UNITS": "'AU-D'", "VEC_TABLE": "'1'",
        "VEC_CORR": "'NONE'", "CSV_FORMAT": "'YES'",
    }
    url = API + "?" + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers={"User-Agent": "BirthChartEphemerisBuilder/2.0"})
    last_error = None
    for attempt in range(3):
        try:
            with urllib.request.urlopen(req, timeout=120) as resp:
                payload = json.loads(resp.read().decode("utf-8"))
            if payload.get("error"):
                raise RuntimeError("JPL Horizons error: " + str(payload["error"]))
            result = payload.get("result", "")
            if "$$SOE" not in result or "$$EOE" not in result:
                raise RuntimeError("No ephemeris block returned:\n" + result[:1500])
            break
        except Exception as error:      # network hiccup: wait and retry
            last_error = error
            time.sleep(3 * (attempt + 1))
    else:
        raise last_error

    block = result.split("$$SOE", 1)[1].split("$$EOE", 1)[0]
    rows = []
    for row in csv.reader(io.StringIO(block)):
        v = [c.strip() for c in row]
        while v and v[-1] == "":
            v.pop()
        if len(v) < 5:
            continue
        rows.append((float(v[0]), float(v[2]), float(v[3]), float(v[4])))
    if len(rows) != count:
        raise RuntimeError(f"{command}: expected {count} samples, got {len(rows)}")
    for i, (jd, *_rest) in enumerate(rows):
        if abs(jd - (JD0 + (first + i) * STEP)) > 1e-3:
            raise RuntimeError(f"{command}: sample {first + i} is not on the 16-day grid (JD {jd})")
    return rows


def build_body(key, command, rmin_rmax):
    rmin, rmax = rmin_rmax
    ints = []
    for first in range(0, COUNT, CHUNK):
        n = min(CHUNK, COUNT - first)
        print(f"  {key}: samples {first}..{first + n - 1}", flush=True)
        for _jd, x, y, z in fetch(command, first, n):
            r = math.sqrt(x * x + y * y + z * z)
            if not (rmin < r < rmax):
                raise RuntimeError(f"{key}: implausible distance {r:.3f} AU - wrong object?")
            ints += [round(x / SCALE), round(y / SCALE), round(z / SCALE)]
        time.sleep(0.5)
    if len(ints) != COUNT * 3:
        raise RuntimeError(f"{key}: wrong sample count")
    return base64.b64encode(struct.pack("<%di" % len(ints), *ints)).decode("ascii")


def main():
    data = {}
    for key, command, rng in BODIES:
        print(f"Fetching {key} ...", flush=True)
        data[key] = build_body(key, command, rng)
    names = json.dumps([b[0] for b in BODIES])
    body = ",".join(f'{k}:"{v}"' for k, v in data.items())
    text = (
        "// Generated by tools/build_ephemeris.py from NASA/JPL Horizons. Do not edit.\n"
        "// Heliocentric, geometric, J2000 ecliptic, AU, UT. int32 LE x,y,z per sample, units of 1e-6 AU.\n"
        f"window.EPH={{jd0:{JD0},step:{STEP},scale:{SCALE:g},names:{names},data:{{{body}}}}};\n"
    )
    OUTPUT.write_text(text, encoding="utf-8")
    print("\nSUCCESS")
    print(f"Created: {OUTPUT}  ({len(text) / 1024:.0f} kB)")


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print("\nERROR: " + str(error))
        print("The ephemeris file was NOT updated.")
    finally:
        input("\nPress Enter to close this window...")
